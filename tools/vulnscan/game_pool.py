import re

VERDICTS = ("양호", "취약", "증거 부족(needs_review)")


def _pat(example):
    return "^" + r"\s+".join(re.escape(w) for w in example.lower().split()) + "$"


def _choices(prefix, items):
    return [{"id": f"{prefix}{i + 1}", "label": s.lstrip("*!"), "correct": s[0] == "*", "isTrap": s[0] == "!"}
            for i, s in enumerate(items)]


def _problem(id, title, type, difficulty, owasp, objective, ally, evidence, hints, flag, cls, verdict, act,
             commands=(), required=(), required_ids=()):
    answer, traps, why_v = verdict
    verdict_items = [("*" if v.startswith(answer) else "!" if v.split("(")[0] in traps else "") + v for v in VERDICTS]
    d = {
        "id": id, "title": title, "type": type, "difficulty": difficulty, "owasp": owasp, "objective": objective,
        "allyOpening": ally,
        "evidence": [{"number": f"E{i + 1}", "title": t, "detail": dt, "tag": tg} for i, (t, dt, tg) in enumerate(evidence)],
        "hints": [{"level": i + 1, "text": t} for i, t in enumerate(hints)],
        "flag": flag,
        "steps": [
            {"key": "classify", "question": "이 기록이 가리키는 문제는?", "choices": _choices("c", cls[:3]), "why": cls[3]},
            {"key": "verdict", "question": "이 상태는?", "choices": _choices("v", verdict_items), "why": why_v},
            {"key": "action", "question": "올바른 조치는?", "choices": _choices("a", act[:3]), "why": act[3]},
        ],
    }
    if type == "terminal":
        cmds = [{"key": "help", "pattern": "^help$", "output": "사용 가능한 명령:\n" + "\n".join(c[1] for c in commands)}]
        cmds += [{"key": k, "pattern": _pat(ex), "output": out, "reveals": list(rev)} for k, ex, out, rev in commands]
        d["commands"], d["requiredActions"] = cmds, list(required)
    else:
        d["requiredIds"] = list(required_ids)
    return d


